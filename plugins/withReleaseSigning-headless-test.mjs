/**
 * Headless checks for the release-signing config plugin (the fifteenth suite).
 *
 * esbuild-bundles the REAL plugins/withReleaseSigning.ts and drives its real
 * transform over a COMMITTED copy of the stock Expo template's
 * android/app/build.gradle. `@expo/config-plugins` is stubbed through an
 * esbuild resolve plugin, the way src/storage/headless-test.mjs stubs
 * react-native-mmkv (AD8, AD27) — the stub records the mod registration so the
 * plugin's wiring is asserted rather than assumed.
 *
 * WHY THIS SUITE EXISTS. The plugin generates the signing configuration for
 * every release build, on Delta's Mac and on any fresh checkout. Its failure
 * mode is the worst kind this repo has: a plugin whose anchors stop matching
 * and which gives up quietly re-emits the Expo template's
 * `release { signingConfig signingConfigs.debug }`, and THAT BUILD SUCCEEDS —
 * emitting an installable debug-signed "release" APK whose wrongness surfaces
 * only later, as an install-time signature mismatch (AD30, AF47, AF49).
 * `tsc` proves the plugin's shape and says nothing about the bytes it emits.
 *
 * THE LOAD-BEARING ASSERTION IS BYTE-IDENTITY. AF42's device evidence — the
 * only release-mode evidence this repo holds — and AD30's three-level fail-safe
 * are properties of the exact hand-edited build.gradle that was on disk when
 * they were established. Replacing a hand edit with generated output would
 * spend that evidence unless the generated bytes are identical. They are, and
 * this suite pins both hashes so they stay that way.
 *
 * THE FIXTURE IS COMMITTED, NOT FETCHED. `npm pack` at test time would put the
 * npm registry inside `npm run check`, and `expo-template-bare-minimum@sdk-57`
 * is a MOVING dist-tag that has already moved once (57.0.22 at AF47, 57.0.23 at
 * AF50). A fetched fixture would make this suite non-deterministic. The
 * committed copy is byte-identical across template 57.0.20-57.0.23 (AF50).
 *
 * IDEMPOTENCE IS NOT A NICETY. A release runs `expo prebuild --no-clean`
 * (AD36 §7), which reuses the existing build.gradle, so the mod re-runs on its
 * own previous output every single release. A transform that only knew "apply"
 * and "throw" would fail every release; the checks below pin the three-way
 * discrimination that makes it work.
 *
 * TWO LOADERS ARE EXERCISED, NOT ONE — the same reasoning as
 * app.config-headless-test.mjs, and it applies here because a `.ts` config
 * plugin is loaded through the SAME @expo/require-utils path as a `.ts` config
 * (plugin-resolver.js:39 and :136). The native stripper accepts only erasable
 * TypeScript, `tsc` does not enforce erasability, and the primary loader
 * accepts an `enum` without complaint — so nothing but this suite would catch
 * a non-erasable construct added later. See AF50.
 */

import assert from 'node:assert/strict';
import { build } from 'esbuild';
import { createHash } from 'node:crypto';
import { readFile, writeFile, unlink } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

// stripTypeScriptTypes is flagged experimental and warns when it is first
// reached. Node installs its own stderr printer as a 'warning' listener at
// startup and an added listener does NOT displace it, so the default one is
// removed first. Everything other than this one warning is re-printed
// unchanged. The handler must be in place BEFORE node:module is reached, and
// static ESM imports hoist above module-body code -- hence the dynamic import.
process.removeAllListeners('warning');
process.on('warning', (w) => {
  if (w.name !== 'ExperimentalWarning' || !/stripTypeScriptTypes/.test(w.message)) {
    console.warn(w);
  }
});

const { stripTypeScriptTypes } = await import('node:module');

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const PLUGIN_TS = path.join(__dirname, 'withReleaseSigning.ts');
const STOCK_FIXTURE = path.join(__dirname, '__fixtures__', 'stock-app-build.gradle');
const RELEASE_SIGNING_DOC = path.join(__dirname, '..', 'RELEASE-SIGNING.md');

/**
 * The hand-edited android/app/build.gradle as it stood when AF42's release-mode
 * device evidence was gathered, and what this plugin must reproduce. Pinned as
 * a literal rather than read from disk: android/ is gitignored, so it does not
 * exist in a fresh checkout or in CI, and this suite must be hermetic.
 *
 * The pin is ARCHIVAL. It describes that specific artifact -- versionCode 1,
 * versionName 1.0.0, package com.arishh.readingaid. Bumping versionCode per
 * AD36 §7 changes the real file's hash and does NOT break this check, because
 * the check recomputes from the fixture rather than reading the disk.
 */
const AF42_BUILD_GRADLE_SHA256 =
  '0b322188fa0661d91389c80c86a65c3d10dbd5996e8dc44d24031f539bdefcb9';

/** The plugin's own output, before Expo's identity mods. What it alone owns. */
const PLUGIN_OUTPUT_SHA256 =
  '06fe1eef76396bf17d73819bda1d57f44e6f4e4e38065dce98ca1bb259172b55';

/** The committed stock fixture, so a silent fixture swap fails loudly. */
const STOCK_FIXTURE_SHA256 =
  'c5056fedcc8225aae86d3432ca48aa1711130987bac10427e68f4e0d6938bd40';

const sha256 = (text) => createHash('sha256').update(text, 'utf8').digest('hex');

/**
 * Expo's OWN identity mods, not this plugin's: Package.withPackageGradle
 * rewrites namespace/applicationId and Version.withVersion rewrites
 * versionName. They are replayed here only so the plugin's output is comparable
 * to the real generated file. They edit three lines the plugin never touches,
 * which is why mod ordering between them and this plugin cannot matter.
 */
function applyExpoIdentityMods(contents) {
  return contents
    .replace(/namespace "com\.helloworld"/, "namespace 'com.arishh.readingaid'")
    .replace(/applicationId "com\.helloworld"/, "applicationId 'com.arishh.readingaid'")
    .replace(/versionName "1\.0"/, 'versionName "1.0.0"');
}

/** Write `code` beside this suite, import it, and always clean up. */
async function importCode(code, tag) {
  const tmpPath = path.join(__dirname, `.headless-signing-${tag}-${process.pid}.mjs`);
  await writeFile(tmpPath, code);
  try {
    return await import(`${tmpPath}?t=${Date.now()}`);
  } finally {
    await unlink(tmpPath);
  }
}

const source = await readFile(PLUGIN_TS, 'utf8');
const stock = await readFile(STOCK_FIXTURE, 'utf8');
const doc = await readFile(RELEASE_SIGNING_DOC, 'utf8');

/**
 * Stub @expo/config-plugins. It is a transitive, unpinned dependency and the
 * suite has no business bundling its graph; more usefully, the stub RECORDS the
 * mod registration so the plugin's wiring can be asserted.
 */
const registrations = [];
const stubConfigPlugins = {
  name: 'stub-expo-config-plugins',
  setup(builder) {
    builder.onResolve({ filter: /^@expo\/config-plugins$/ }, () => ({
      path: 'expo-config-plugins-stub',
      namespace: 'stub',
    }));
    builder.onLoad({ filter: /.*/, namespace: 'stub' }, () => ({
      contents: `
        export const withAppBuildGradle = (config, action) => {
          globalThis.__withReleaseSigningRegistrations.push({ config, action });
          return config;
        };
      `,
      loader: 'js',
    }));
  },
};
globalThis.__withReleaseSigningRegistrations = registrations;

// Loader 1 -- esbuild, standing in for typescript's transpileModule.
const bundled = await build({
  entryPoints: [PLUGIN_TS],
  bundle: true,
  write: false,
  format: 'esm',
  target: 'node18',
  platform: 'node',
  plugins: [stubConfigPlugins],
});
const viaEsbuild = await importCode(bundled.outputFiles[0].text, 'esbuild');

// Loader 2 -- Node's native stripper, the real fallback path. If the plugin
// ever stops being erasable, this throws and the suite fails here. It imports
// the REAL @expo/config-plugins, which additionally proves the specifier
// resolves from this directory.
let strippedSource = null;
let strippedError = null;
try {
  strippedSource = stripTypeScriptTypes(source);
} catch (err) {
  strippedError = err;
}
let viaStripper = null;
if (strippedSource !== null) {
  try {
    viaStripper = await importCode(strippedSource, 'stripped');
  } catch (err) {
    strippedError = err;
  }
}

const transform = viaEsbuild.transformAppBuildGradle;

let passed = 0;
let failed = 0;

function check(label, actual, expected) {
  try {
    assert.deepStrictEqual(actual, expected);
    console.log(`  PASS  ${label}`);
    passed++;
  } catch (err) {
    console.log(`  FAIL  ${label}: ${err.message}`);
    failed++;
  }
}

function ok(label, cond, msg) {
  try {
    assert.ok(cond, msg);
    console.log(`  PASS  ${label}`);
    passed++;
  } catch (err) {
    console.log(`  FAIL  ${label}: ${err.message}`);
    failed++;
  }
}

/**
 * Evaluate `fn` and return its value, or a marker string if it threw.
 *
 * Every transform below runs against a DELIBERATELY BROKEN plugin during
 * negative-control runs, and an unexpected throw in an argument position would
 * abort the whole file -- hiding every later check behind the first failure,
 * which is the fail-fast masking AF17 records and this repo deliberately avoids.
 * The marker is a string, so downstream `.includes` checks degrade to a clean
 * FAIL instead of a crash.
 */
function value(fn) {
  try {
    return fn();
  } catch (err) {
    return `THREW: ${err.message}`;
  }
}

/** Assert that `fn` throws, and that its message mentions `needle`. */
function throws(label, fn, needle) {
  try {
    fn();
    console.log(`  FAIL  ${label}: did not throw`);
    failed++;
  } catch (err) {
    if (needle && !err.message.includes(needle)) {
      console.log(`  FAIL  ${label}: threw, but message lacked ${JSON.stringify(needle)} — ${err.message}`);
      failed++;
      return;
    }
    console.log(`  PASS  ${label}`);
    passed++;
  }
}

console.log('\nrelease-signing config plugin — headless checks\n');

// ─── 1. Erasability, and the two loader paths ───────────────────────────────
{
  ok(
    'withReleaseSigning.ts is ERASABLE TypeScript (node stripTypeScriptTypes accepts it)',
    strippedError === null,
    `stripTypeScriptTypes threw: ${strippedError && strippedError.message}`,
  );

  ok('both loader paths produced a transform function',
    typeof viaEsbuild.transformAppBuildGradle === 'function' &&
      typeof (viaStripper && viaStripper.transformAppBuildGradle) === 'function',
    `esbuild=${typeof viaEsbuild.transformAppBuildGradle} stripper=${typeof (viaStripper && viaStripper.transformAppBuildGradle)}`);

  ok('both loader paths produced a default-exported plugin function',
    typeof viaEsbuild.default === 'function' &&
      typeof (viaStripper && viaStripper.default) === 'function',
    'default export missing from one loader');

  if (viaStripper && typeof viaStripper.transformAppBuildGradle === 'function') {
    check(
      'the two loaders transform the stock template identically',
      value(() => viaStripper.transformAppBuildGradle(stock)),
      value(() => transform(stock)),
    );
  }
}

// ─── 2. Byte-identity — the acceptance criterion ────────────────────────────
{
  check('the committed stock fixture is the template bytes it claims to be',
    sha256(stock), STOCK_FIXTURE_SHA256);

  const signed = value(() => transform(stock));

  ok('the transform actually changed the template', signed !== stock,
    'transform returned the stock template unchanged');

  check("the plugin's own output matches its pinned hash",
    sha256(signed), PLUGIN_OUTPUT_SHA256);

  check("transform(stock) + Expo's identity mods reproduces AF42's build.gradle EXACTLY",
    sha256(applyExpoIdentityMods(signed)), AF42_BUILD_GRADLE_SHA256);

  // The plugin must touch NOTHING outside the three regions it owns. Expo's
  // three identity lines are the only differences it may leave behind.
  const a = signed.split('\n');
  const b = applyExpoIdentityMods(signed).split('\n');
  const differing = a.map((line, i) => (line === b[i] ? null : line)).filter((l) => l !== null);
  check('the only lines Expo owns are namespace / applicationId / versionName', differing, [
    '    namespace "com.helloworld"',
    '        applicationId "com.helloworld"',
    '        versionName "1.0"',
  ]);
}

// ─── 3. Anchors — every miss must THROW, never no-op ────────────────────────
{
  throws('a missing `android {` anchor throws',
    () => transform(stock.replace('\nandroid {\n', '\nandroid  {\n')), 'android-block');

  throws('a missing signingConfigs anchor throws',
    () => transform(stock.replace("            storeFile file('debug.keystore')\n", '')),
    'signing-configs');

  throws('a missing release-buildType anchor throws',
    () => transform(stock.replace('            // Caution! In production, you need to generate your own keystore file.\n', '')),
    'release-build-type');

  throws('an AMBIGUOUS anchor throws rather than picking one',
    () => transform(stock.replace('\nandroid {\n', '\nandroid {\n\nandroid {\n')), 'android-block');

  throws('the thrown message names the artifact at risk',
    () => transform(stock.replace('\nandroid {\n', '\nandroid  {\n')), 'DEBUG-SIGNED');

  throws('the thrown message points at the documentation',
    () => transform(stock.replace('\nandroid {\n', '\nandroid  {\n')), 'RELEASE-SIGNING.md');
}

// ─── 4. Idempotence — what `prebuild --no-clean` depends on ─────────────────
{
  const once = value(() => transform(stock));
  const twice = value(() => transform(once));
  check('applying twice equals applying once', twice, once);
  check('applying three times still equals applying once', value(() => transform(twice)), once);

  // Partial application is corruption, not a state to repair by guesswork.
  throws('a PARTIALLY applied file throws',
    () => transform(once.replace(viaEsbuild.SIGNING_BLOCKS.releaseBuildType, '            signingConfig null')),
    'PARTIALLY');

  // Fully applied but the template default somehow also present.
  throws('applied-AND-template-default-present throws',
    () => transform(once.replace(
      '    buildTypes {\n        debug {\n',
      '    buildTypes {\n' +
        '            // Caution! In production, you need to generate your own keystore file.\n' +
        '            // see https://reactnative.dev/docs/signed-apk-android.\n' +
        '            signingConfig signingConfigs.debug\n' +
        '        debug {\n',
    )),
    'inconsistent state');
}

// ─── 5. The output must never be debug-signed ───────────────────────────────
{
  const signed = value(() => transform(stock));

  ok('the template\'s release signingConfig default is GONE',
    !signed.includes(
      '            // Caution! In production, you need to generate your own keystore file.\n' +
        '            // see https://reactnative.dev/docs/signed-apk-android.\n' +
        '            signingConfig signingConfigs.debug\n',
    ),
    'the debug-signing default survived the transform');

  ok('buildTypes.release is the releaseSigningError ternary',
    signed.includes('            signingConfig releaseSigningError == null ? signingConfigs.release : null\n'),
    'the release buildType is not wired to signingConfigs.release');

  // THE TRAP: `signingConfig signingConfigs.debug` occurs TWICE in the stock
  // template, and the buildTypes.debug occurrence is CORRECT. A transform that
  // anchored on the bare statement would match both and silently break debug
  // signing -- with no test noticing, because the release half would look right.
  ok('buildTypes.debug STILL signs with signingConfigs.debug',
    signed.includes('    buildTypes {\n        debug {\n            signingConfig signingConfigs.debug\n        }\n'),
    'the debug buildType lost its signing config');

  // Counted as an EXECUTABLE STATEMENT (twelve-space indent, whole line), not
  // as a substring: the preamble this plugin inserts quotes the template
  // default inside a comment, so a naive substring count reads 2 and looks like
  // a failure. The statement form is what actually signs anything.
  const statement = /^ {12}signingConfig signingConfigs\.debug$/gm;
  check('the stock template has TWO debug-signing statements',
    (stock.match(statement) || []).length, 2);
  check('exactly ONE remains after the transform -- buildTypes.debug',
    (signed.match(statement) || []).length, 1);

  ok('the taskGraph.whenReady hard-fail guard is present',
    signed.includes('gradle.taskGraph.whenReady { taskGraph ->') &&
      signed.includes('throw new GradleException('),
    'the AD30 guard is missing from the generated file');

  ok('signingConfigs.release is populated only when the keystore resolves',
    signed.includes('        release {\n') && signed.includes('            if (releaseSigningError == null) {\n'),
    'signingConfigs.release is missing or unguarded');

  ok('no keystore password or alias value is baked into the generated file',
    !/storePassword\s+'(?!android')/.test(signed) &&
      signed.includes("storePassword keystoreProperties.getProperty('storePassword')"),
    'a credential literal appears to have been inlined');
}

// ─── 6. The plugin's wiring, via the recording stub ─────────────────────────
{
  registrations.length = 0;
  const inputConfig = { name: 'Reading Aid' };
  const returned = viaEsbuild.default(inputConfig);

  check('the plugin registered exactly one appBuildGradle mod', registrations.length, 1);
  check('it returned the config it was handed', returned, inputConfig);

  const { action } = registrations[0];
  ok('the registered mod is a function', typeof action === 'function', `got ${typeof action}`);

  const modConfig = { modResults: { language: 'groovy', contents: stock } };
  const result = value(() => action(modConfig));
  check('the mod transforms modResults.contents in place',
    result && result.modResults ? result.modResults.contents : result,
    value(() => transform(stock)));

  throws('a non-Groovy build.gradle throws rather than being guessed at',
    () => action({ modResults: { language: 'kt', contents: stock } }), 'not Groovy');
}

// ─── 7. RELEASE-SIGNING.md §3 must still describe what is generated ─────────
//
// Ruling 1: §3's prose copy is kept as a fallback, so it is a second copy of
// the same Gradle text. This is the mechanism that keeps it honest.
{
  const blocks = viaEsbuild.SIGNING_BLOCKS;
  const fenced = [...doc.matchAll(/```gradle\n([\s\S]*?)```/g)].map((m) => m[1].replace(/\n$/, ''));

  check('RELEASE-SIGNING.md §3 still carries exactly four gradle blocks', fenced.length, 4);

  check('§3a preamble matches the plugin byte for byte', fenced[0], blocks.preamble);
  check('§3b signingConfigs.release matches the plugin byte for byte', fenced[1], blocks.releaseSigningConfig);
  check('§3c template anchor matches the plugin byte for byte', fenced[2], blocks.templateReleaseBuildType);
  check('§3c replacement matches the plugin byte for byte', fenced[3], blocks.releaseBuildType);

  ok('§3 is marked as a fallback rather than the mechanism',
    /FALLBACK/.test(doc) && /withReleaseSigning/.test(doc),
    'RELEASE-SIGNING.md §3 does not name the plugin as the live mechanism');

  ok('the demotion states the condition that would retire §3',
    doc.includes(AF42_BUILD_GRADLE_SHA256),
    'RELEASE-SIGNING.md does not pin the hash that would retire §3');
}

console.log(`\n${passed} passed, ${failed} failed\n`);
process.exit(failed === 0 ? 0 : 1);
